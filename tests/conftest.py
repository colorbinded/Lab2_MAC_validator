def valid_mac_addresses() -> list[str]:
    """Набор синтаксически корректных MAC-адресов"""
    return [
        "00:1A:2B:3C:4D:5E",
        "ff:ff:ff:ff:ff:ff",
        "00-1A-2B-3C-4D-5E",
        "a0-b1-c2-d3-e4-f5",
        "001A.2B3C.4D5E",
        "aBcD.1234.ef56",
    ]


@pytest.fixture(scope="session")
def invalid_mac_addresses() -> list[str]:
    """Набор заведомо некорректных MAC-адресов"""
    return [
        "",  # Пустая строка.
        "00:1A:2B:3C:4D",  # Только пять октетов вместо шести
        "00:1A:2B:3C:4D:5E:6F",  # Семь октетов вместо шести
        "00:1A:2B:3C:4D:5G",  # Символ G не является шестнадцатеричным (конец)
        "GG:1A:2B:3C:4D:5E",  # Символ G не является шестнадцатеричным (начало)
        "00-1A:2B-3C:4D-5E",  # Смешаны дефисы и двоеточия
        "001A.2B3C.4D5",  # Последняя группа содержит только три символа
        "001A-2B3C-4D5E",  # Для формата cisco нужны точки а не дефисы
        " 00:1A:2B:3C:4D:5E",  # Пробел перед адресом
        "00:1A:2B:3C:4D:5E ",  # Пробел после адреса
        "00:1A:2B:3C:4D:5E\n",  # Перевод строки после адреса
        "00:1A:2B:3C:4D:5",  # Последний октет содержит один символ
        "00::1A:2B:3C:4D:5E",  # Двойное двоеточие
        "00:1A:2B:3C:4D:5E:ZZ",  # Лишняя группа с недопустимыми символами
        "GGGG.2B3C.4D5E",  # Символ G не является шестнадцатеричным (формат cisco)
        "001A.2B3C.4D5E.extra",  # После адреса есть лишний текст
        "not-a-mac-address",  # Строка не соответствует ни одному формату
    ]
